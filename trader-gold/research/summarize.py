#!/usr/bin/env python3
"""Summarize the saved trader-gold research reports into repeatable tables.

Run from anywhere:

    python3 trader-gold/research/summarize.py

It writes iterations.json and iterations.md next to this script. Only saved
report.json files are read; raw market CSV files are intentionally external.
"""

import json
import os


ROOT = os.path.dirname(os.path.abspath(__file__))


def load_reports():
    rows = []
    for name in sorted(os.listdir(ROOT)):
        path = os.path.join(ROOT, name, "report.json")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as handle:
            report = json.load(handle)
        data = report["data"]
        validation = report["validation"]
        checks = validation["checks"]
        failed = sorted(key for key, value in checks.items() if not value)
        rows.append({
            "run": name,
            "mode": report["mode"],
            "status": report["status"],
            "deployment_status": report["deployment_status"],
            "created_at_utc": report["created_at_utc"],
            "config_hash": report["config_hash"],
            "data": {
                "rows": data.get("rows"),
                "start": data.get("start"),
                "end": data.get("end"),
                "synthetic": data.get("synthetic"),
                "coverage_pass": data.get("coverage_pass"),
                "source_url": data.get("source_url"),
                "source_description": data.get("source_description"),
                "sha256": data.get("sha256"),
                "warnings": data.get("warnings"),
            },
            "summary": validation["summary"],
            "checks": checks,
            "failed_gates": failed,
            "ea_static_pass": report["ea_review"]["static_pass"],
            "ea_compiled": report["ea_review"]["compiled"],
            "ea_mt5_tick_test_passed": report["ea_review"]["mt5_tick_test_passed"],
        })
    return rows


def number(value, digits=2):
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return ("%.*f" % (digits, value)).rstrip("0").rstrip(".")
    return str(value)


def markdown(rows):
    lines = [
        "# Saved research iterations",
        "",
        "Generated by `python3 trader-gold/research/summarize.py`.",
        "",
        "| Run | Data start | Rows | Status | Folds | OOS trades | OOS net | OOS PF | Positive folds | Stress net | Coverage | Failed gates |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        summary = row["summary"]
        data = row["data"]
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            row["run"], data["start"] or "n/a", data["rows"] or 0, row["status"],
            summary.get("folds", 0), summary.get("oos_trades", 0),
            number(summary.get("oos_net_profit")), number(summary.get("oos_profit_factor")),
            "%s/%s" % (summary.get("positive_folds", 0), summary.get("folds", 0)),
            number(summary.get("stress_net_profit")),
            "PASS" if data["coverage_pass"] else "FAIL",
            ", ".join(row["failed_gates"]) or "none",
        ))
    lines.extend([
        "",
        "Every run keeps `deployment_status: MT5_VALIDATION_REQUIRED`.",
        "A synthetic run is software evidence only. A real or proxy run that fails a gate is",
        "not a professional bot and is not approved for live trading.",
        "",
    ])
    return "\n".join(lines)


def main():
    rows = load_reports()
    with open(os.path.join(ROOT, "iterations.json"), "w", encoding="utf-8") as handle:
        json.dump(rows, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")
    with open(os.path.join(ROOT, "iterations.md"), "w", encoding="utf-8") as handle:
        handle.write(markdown(rows))
    print("Wrote %d research iterations to %s" % (len(rows), ROOT))


if __name__ == "__main__":
    main()
